import { isInstant } from './datetime'

// TASK-020 Phase 3 자체 리뷰(RC-4 변종) — 서버 시각(ISO 순간)은 형식뿐 아니라 달력에 있는 날짜·시각이어야 한다.
// Date.parse 는 2026-02-30 을 3월 2일로, T24:00:00 을 다음 날 0시로 읽는다. SoT: SCENARIO_TASK-020.md 규약 「계약 위반」
describe('TASK-020 isInstant', () => {
  test.each([
    ['Z', '2026-11-11T09:00:00Z'],
    ['소수 초 3자리', '2026-11-11T09:00:00.123Z'],
    ['소수 초 9자리(Instant 나노초)', '2026-11-11T09:00:00.123456789Z'],
    ['+09:00 오프셋', '2026-11-11T18:00:00+09:00'],
    ['윤년 2월 29일', '2028-02-29T00:00:00Z'],
    ['23:59:59', '2026-11-11T23:59:59Z'],
    ['연도 0099 (두 자리 연도 보정에 걸리지 않는다)', '0099-01-01T00:00:00Z'],
    ['연도 0001', '0001-01-01T00:00:00+23:59'],
    ['연도 0000', '0000-01-01T00:00:00Z'],
  ])('ISO 순간이다 — %s', (_label, value) => {
    expect(isInstant(value)).toBe(true)
  })

  test.each([
    ['형식: 1', '1'],
    ['형식: 연도만', '2026'],
    ['형식: 날짜만', '2026-11-11'],
    ['형식: 오프셋 없음', '2026-11-11T09:00:00'],
    ['형식: 숫자', 1731315600000],
    ['달력: 2월 30일', '2026-02-30T10:00:00Z'],
    ['달력: 4월 31일', '2026-04-31T00:00:00Z'],
    ['달력: 평년 2월 29일', '2026-02-29T00:00:00Z'],
    ['달력: 13월', '2026-13-01T00:00:00Z'],
    ['달력: 0일', '2026-11-00T00:00:00Z'],
    ['시각: 24시', '2026-11-16T24:00:00Z'],
    ['시각: 60분', '2026-11-16T10:60:00Z'],
    ['시각: 60초', '2026-11-16T10:00:60Z'],
    ['오프셋: +24:00', '2026-11-16T10:00:00+24:00'],
    ['오프셋: +09:60', '2026-11-16T10:00:00+09:60'],
  ])('ISO 순간이 아니다 — %s', (_label, value) => {
    expect(isInstant(value)).toBe(false)
  })
})
